"""Port an implemented VIP to an updated specification with a three-way merge.

A VIP generated by this flow is a deterministic function of its configuration (vip_config.json)
and of the generation metadata (author, project, date in spec/vip_generation.json). The work an
agent or a person did on top of the generated skeleton is therefore exactly the difference between
the current tree and the skeleton regenerated from the OLD configuration. Porting regenerates the
skeleton for the OLD and for the NEW configuration and merges, file by file:

    base   skeleton from the old configuration
    ours   the current tree (generated plus hand-written code)
    theirs skeleton from the new configuration

    ours == base          take theirs                (nothing was written by hand: new skeleton)
    theirs == base        keep ours                  (the change does not touch this file)
    all three differ      git merge-file             (hand-written code kept, new skeleton merged in;
                                                      overlapping edits become conflict markers)
    new file              take theirs;  removed file: dropped when untouched, kept when modified
    base/ and spec/       always theirs               (the base library and the copies of the spec)

Conflict markers (<<<<<<<) fail `vip lint impl` until they are resolved. The output directory is new;
the current tree is never modified.

Usage:
    python vip_port.py --current DIR --old-config FILE --new-config FILE --out-dir DIR
        --requirements requirements.csv [--report port_report.md]
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import vip_common as vc  # noqa: E402

NL = chr(10)


def load_generator():
    for cand in [HERE / "gen_vip_skeleton.py", *sorted(HERE.parent.parent.glob("*/scripts/gen_vip_skeleton.py"))]:
        if cand.is_file():
            spec = importlib.util.spec_from_file_location("gen_vip_skeleton", cand)
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            return mod
    raise SystemExit("error: gen_vip_skeleton.py not found; install the vlsit-vip-generator skill next to this one")


def read_tree(root: Path) -> dict[str, str]:
    out = {}
    for p in sorted(root.rglob("*")):
        if p.is_file() and "__pycache__" not in p.parts:
            out[p.relative_to(root).as_posix()] = p.read_text(encoding="utf-8", errors="replace").replace("\r\n", NL)
    return out


def merge3(cur: str, base: str, new: str, name: str) -> tuple[str, int]:
    with tempfile.TemporaryDirectory() as d:
        fc, fb, fn = (Path(d) / x for x in ("current", "base", "new"))
        fc.write_text(cur, encoding="utf-8", newline=NL)
        fb.write_text(base, encoding="utf-8", newline=NL)
        fn.write_text(new, encoding="utf-8", newline=NL)
        r = subprocess.run(["git", "merge-file", "-p", "-L", f"current:{name}", "-L", f"base:{name}", "-L", f"new:{name}",
                            str(fc), str(fb), str(fn)], capture_output=True, text=True, encoding="utf-8")
        if r.returncode < 0 or r.returncode > 127:
            raise SystemExit(f"error: git merge-file failed for {name}: {r.stderr.strip()}")
        return r.stdout, r.returncode


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--current", required=True, help="the existing VIP tree <tag>_vip (with hand-written code)")
    ap.add_argument("--old-config", required=True, help="the vip_config.json the current tree was generated from")
    ap.add_argument("--new-config", required=True, help="vip_config.json derived from the updated specification")
    ap.add_argument("--out-dir", required=True, help="the ported tree to create (must not exist)")
    ap.add_argument("--requirements", required=True, help="requirements.csv of the updated specification")
    ap.add_argument("--report")
    a = ap.parse_args()
    out = Path(a.out_dir)
    vc.refuse_overwrite(out)
    cur_root = Path(a.current)
    meta_p = cur_root / "spec" / "vip_generation.json"
    if not meta_p.is_file():
        raise SystemExit("error: the current tree has no spec/vip_generation.json; it was not generated by this flow version. "
                         "Use the impact analysis and edit in place instead of porting")
    meta = json.loads(meta_p.read_text(encoding="utf-8"))
    gen = load_generator()
    old_cfg = json.loads(Path(a.old_config).read_text(encoding="utf-8"))
    new_cfg = json.loads(Path(a.new_config).read_text(encoding="utf-8"))
    if old_cfg["tag"] != new_cfg["tag"] or old_cfg["profile"] != new_cfg["profile"]:
        raise SystemExit("error: the tag and the profile must not change in a port")
    base = gen.build(old_cfg, meta["author"], meta["project"], meta["date"])
    new = gen.build(new_cfg, meta["author"], meta["project"], meta["date"])
    cur = read_tree(cur_root)
    new["spec/requirements.csv"] = Path(a.requirements).read_text(encoding="utf-8")
    base["spec/requirements.csv"] = cur.get("spec/requirements.csv", "")
    new["spec/vip_generation.json"] = json.dumps({**meta, "version": new_cfg["version"]}, indent=2) + NL

    stats = {"new skeleton": [], "kept hand-written": [], "merged": [], "conflict": [], "added": [], "restored": [],
             "removed": [], "removed but modified (kept)": [], "user-added (kept)": [], "unchanged": []}
    result: dict[str, str] = {}
    for f in sorted(set(base) | set(new) | set(cur)):
        b, n, c = base.get(f), new.get(f), cur.get(f)
        always_new = f.startswith(("base/", "spec/"))
        if n is not None and always_new:
            result[f] = n
            (stats["unchanged"] if c == n else stats["new skeleton"]).append(f)
        elif b is not None and n is not None and c is not None:
            if c == b:
                result[f] = n
                (stats["unchanged"] if n == b else stats["new skeleton"]).append(f)
            elif n == b:
                result[f] = c
                stats["kept hand-written"].append(f)
            else:
                merged, conflicts = merge3(c, b, n, f)
                result[f] = merged
                (stats["conflict"] if conflicts else stats["merged"]).append(f)
        elif b is not None and n is not None and c is None:
            result[f] = n
            stats["restored"].append(f)
        elif b is None and n is not None:
            if c is None:
                result[f] = n
                stats["added"].append(f)
            else:
                result[f] = c
                stats["user-added (kept)"].append(f + " (also in the new skeleton; compare by hand)")
        elif n is None and b is not None:
            if c is not None and c != b:
                result[f] = c
                stats["removed but modified (kept)"].append(f)
            else:
                stats["removed"].append(f)
        elif c is not None:
            result[f] = c
            stats["user-added (kept)"].append(f)
    for f, text in result.items():
        p = out / f
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline=NL)
    lines = [f"# Port report: {old_cfg['version']} -> {new_cfg['version']}", ""]
    for k, v in stats.items():
        lines.append(f"- {k}: {len(v)}")
    for k in ("conflict", "merged", "removed but modified (kept)", "user-added (kept)", "added", "removed"):
        if stats[k]:
            lines += ["", f"## {k}", ""] + [f"- {x}" for x in stats[k]]
    report = NL.join(lines) + NL
    if a.report:
        vc.refuse_overwrite(a.report)
        Path(a.report).write_text(report, encoding="utf-8", newline=NL)
    print("port: " + ", ".join(f"{k} {len(v)}" for k, v in stats.items() if v))
    if stats["conflict"]:
        print("CONFLICTS to resolve (search for <<<<<<<): " + ", ".join(stats["conflict"][:8]))
    if stats["removed but modified (kept)"]:
        print("removed in the new skeleton but modified here (review): " + ", ".join(stats["removed but modified (kept)"][:6]))
    return 1 if stats["conflict"] else 0


if __name__ == "__main__":
    sys.exit(main())

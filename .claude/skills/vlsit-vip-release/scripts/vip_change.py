"""Change-run support of the VLSIT ASIC VIP Design AI Flow: delta, carry, adopt, start.

Commands
    delta  OLD.md NEW.md [--out FILE] [--json FILE]
           row-level difference of two specifications, table by table, by ID; suggests the version bump
    carry  --evidence NEW --base-evidence OLD --impact impact.json --base-run NAME
           copy PASS entries of the base qualification evidence for traces the change does not touch
    adopt  --code DIR --out DIR
           copy existing VIP code into the run as the base tree for bugfix and feature runs
    layout DIR
           print `flow` (generated by this flow, has spec/vip_generation.json) or `external`
The functions start_change() and bump() are used by vip_state.py when a bugfix or feature run starts.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import vip_common as vc  # noqa: E402

NL = chr(10)
SKIP_KINDS = {"trace", "glossary", "compliance", "candidates", "environment", "timing", "clocks"}
INTERFACE_KINDS = {"signals", "parameters", "knobs", "items"}
CHANGE_REQUEST = """# Change request

## Title
(fill)

## Requirement from the user
(fill: what the VIP must do or support, in the user's words)

## Motivation and source
(fill: standard clause, project need, or the bug that led here)

## Acceptance
(fill: observable criteria, how a user of the VIP sees the new behavior)

## Compatibility
(fill: default behavior must stay the same unless stated here)
"""


# ---------------------------------------------------------------- version and layout

def bump(version: str, kind: str) -> str:
    m = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", version.strip() or "0.1.0")
    major, minor, patch = (int(x) for x in m.groups()) if m else (0, 1, 0)
    if kind == "major":
        return f"{major + 1}.0.0"
    if kind == "minor":
        return f"{major}.{minor + 1}.0"
    return f"{major}.{minor}.{patch + 1}"


def layout_of(tree: Path) -> str:
    return "flow" if (tree / "spec" / "vip_generation.json").is_file() else "external"


def tree_version(tree: Path, default: str = "0.1.0") -> str:
    p = tree / "spec" / "vip_config.json"
    if p.is_file():
        try:
            return json.loads(p.read_text(encoding="utf-8")).get("version", default)
        except json.JSONDecodeError:
            return default
    return default


# ---------------------------------------------------------------- delta

def table_rows(spec: vc.Spec, kind: str) -> dict[str, dict]:
    out: dict[str, dict] = {}
    cols = [vc.norm_key(c) for c in vc.TABLE_SCHEMAS[kind]["columns"]]
    for r in spec.rows(kind):
        key = r.get(cols[0], "").strip()
        if kind == "checkexpr" or key in out:
            key = key or "?"
        out[key] = {c: r.get(c, "").strip() for c in cols}
    return out


def spec_delta(old: vc.Spec, new: vc.Spec) -> dict:
    res: dict = {"front": {}, "tables": {}}
    for k in sorted(set(old.front) | set(new.front)):
        if old.front.get(k) != new.front.get(k):
            res["front"][k] = [old.front.get(k, ""), new.front.get(k, "")]
    for kind in vc.TABLE_SCHEMAS:
        if kind in SKIP_KINDS:
            continue
        a, b = table_rows(old, kind), table_rows(new, kind)
        added = sorted(set(b) - set(a))
        removed = sorted(set(a) - set(b))
        changed = {}
        for k in sorted(set(a) & set(b)):
            diff = {c: [a[k][c], b[k][c]] for c in a[k] if a[k][c] != b[k].get(c, "")}
            if diff:
                changed[k] = diff
        if added or removed or changed:
            res["tables"][kind] = {"added": added, "removed": removed, "changed": changed}
    t = res["tables"]
    breaking = bool(t.get("requirements", {}).get("removed") or t.get("signals", {}).get("removed")
                    or t.get("signals", {}).get("changed") or t.get("knobs", {}).get("removed")
                    or t.get("parameters", {}).get("removed"))
    additive = any(v["added"] for v in t.values())
    behavioral = any(v["changed"] for k, v in t.items() if k in ("requirements", "checkexpr", "caps", "injections", "boundaries"))
    res["version_bump"] = "major" if breaking else "minor" if additive or behavioral else "patch"
    res["interface_change"] = any(k in INTERFACE_KINDS for k in t)
    return res


def render_delta(d: dict, old: str, new: str) -> str:
    L = ["# Specification delta", "", f"Base: `{old}`", f"New: `{new}`", f"Generated: {vc.now_iso()}", "",
         f"Suggested version bump: **{d['version_bump']}**" + ("; the interface changes (signals, parameters, knobs, or item fields)" if d["interface_change"] else ""), ""]
    if d["front"]:
        L += ["## Front matter", ""] + [f"- {k}: `{o}` -> `{n}`" for k, (o, n) in d["front"].items()] + [""]
    for kind, v in d["tables"].items():
        L += [f"## {kind}", ""]
        if v["added"]:
            L.append("- Added: " + ", ".join(v["added"]))
        if v["removed"]:
            L.append("- Removed: " + ", ".join(v["removed"]) + (" (IDs are permanent: mark a requirement `withdrawn` instead)" if kind == "requirements" else ""))
        for k, diff in v["changed"].items():
            for c, (o, n) in diff.items():
                L.append(f"- Changed {k}.{c}: `{o}` -> `{n}`")
        L.append("")
    if not d["tables"] and not d["front"]:
        L.append("No difference.")
    return NL.join(L) + NL


def cmd_delta(a: argparse.Namespace) -> int:
    old, new = vc.load_spec(a.old), vc.load_spec(a.new)
    d = spec_delta(old, new)
    parts = [f"{k} +{len(v['added'])} -{len(v['removed'])} ~{len(v['changed'])}" for k, v in d["tables"].items()]
    print("delta: " + ("; ".join(parts) if parts else "no table difference") + f"; suggested bump: {d['version_bump']}")
    if d["tables"].get("requirements", {}).get("removed"):
        print("warning: requirement rows were removed; keep them with status withdrawn (VNAM-03)")
    if a.out:
        vc.refuse_overwrite(a.out)
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text(render_delta(d, a.old, a.new), encoding="utf-8", newline=NL)
        print(f"delta written to {a.out}")
    if a.json:
        vc.refuse_overwrite(a.json)
        vc.write_json(a.json, d)
    return 0


# ---------------------------------------------------------------- carry

def cmd_carry(a: argparse.Namespace) -> int:
    ev_p = Path(a.evidence)
    ev = json.loads(ev_p.read_text(encoding="utf-8"))
    old = json.loads(Path(a.base_evidence).read_text(encoding="utf-8"))
    imp = json.loads(Path(a.impact).read_text(encoding="utf-8"))
    rerun = set(imp.get("tests_to_run", [])) | set(a.rerun or [])
    prev = {(e["test"], e["variant"]): e for e in old["entries"]}
    carried = fresh = 0
    for e in ev["entries"]:
        o = prev.get((e["test"], e["variant"]))
        if o and o["status"] == "PASS" and e["test"] not in rerun and imp.get("scope") != "full":
            e.update({"status": "PASS", "seeds": o["seeds"], "log": f"carried:{a.base_run}/{o['log']}",
                      "note": f"carried from {a.base_run}: the change does not touch this trace"})
            carried += 1
        else:
            fresh += 1
    added = 0
    if a.bug_log and Path(a.bug_log).is_file():
        known = {e["test"] for e in ev["entries"]}
        for b in vc.read_csv(a.bug_log):
            t = b["regression_test"].strip()
            if t and t not in known and b["status"] in ("fixed", "verified", "closed"):
                for v in ev["variants"]:
                    ev["entries"].append({"test": t, "variant": v, "kind": "reg", "req_id": (b["req_ids"].split(";")[0].split(",")[0].strip() or ""),
                                          "chk_id": "", "status": "NOT_RUN", "seeds": [], "log": "",
                                          "note": f"regression test of {b['bug_id']}"})
                    added += 1
                known.add(t)
        fresh += added
    ev.setdefault("history", []).append({"time": vc.now_iso(), "event": "carry",
                                          "detail": f"{carried} entr(ies) carried from {a.base_run}, {fresh} to run"})
    ev_p.write_text(json.dumps(ev, indent=2) + NL, encoding="utf-8")
    print(f"carried {carried} PASS entr(ies) from {a.base_run}; {fresh} entr(ies) NOT_RUN (run these)"
          + (f"; {added} regression-test entr(ies) added" if added else ""))
    return 0


# ---------------------------------------------------------------- adopt and layout

IGNORED = shutil.ignore_patterns(".git", "__pycache__", "*.pyc", "*.log", "*.wlf", "*.vcd", "*.fsdb", "obj_dir", "work")


def cmd_adopt(a: argparse.Namespace) -> int:
    src, out = Path(a.code), Path(a.out)
    if not src.is_dir():
        raise SystemExit(f"error: code directory not found: {src}")
    vc.refuse_overwrite(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(src, out, ignore=IGNORED)
    n = sum(1 for p in out.rglob("*") if p.is_file())
    print(f"adopted {n} file(s) from {src} into {out} (layout external: later runs use Gates 1, 3, 4 and the project's regression)")
    return 0


# ---------------------------------------------------------------- start of a change run

def copy_into(src: Path, dst: Path) -> None:
    if src.is_dir():
        shutil.copytree(src, dst, ignore=IGNORED, dirs_exist_ok=True)
    elif src.is_file():
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)


def start_change(mode: str, base_run: Path, run: Path, tag: str, st: dict) -> None:
    """Prepare a bugfix or feature run from a finished base run. Changes st in place; never touches the base."""
    bst = json.loads((base_run / "vip_state.json").read_text(encoding="utf-8"))
    if bst["tag"] != tag:
        raise SystemExit(f"error: the base run is for tag '{bst['tag']}', not '{tag}'")
    if bst["gates"]["G1"]["status"] != "APPROVED":
        raise SystemExit("error: the base run has no approved specification (Gate 1); finish or approve it first")
    base_tree = base_run / "04_vip" / f"{tag}_vip"
    if not base_tree.is_dir():
        raise SystemExit(f"error: the base run has no VIP tree at {base_tree}; generate it, or adopt the code in a reverse run (vip adopt)")
    base_spec = base_run / "01_spec" / f"{tag}_vip_spec.md"
    lay = bst.get("layout", "flow")
    base_version = bst["settings"].get("version") or tree_version(base_tree)
    new_version = bump(base_version, "patch" if mode == "bugfix" else "minor")
    settings = {k: v for k, v in bst["settings"].items() if v}
    settings["version"] = new_version
    st["settings"] = settings
    st.update({"mode": mode, "layout": lay, "base_run": str(base_run.resolve())})
    (run / "00_change").mkdir()
    (run / "00_base").mkdir()
    vc.write_json(run / "00_base" / "base.json", {
        "run": base_run.name, "path": str(base_run.resolve()), "version": base_version, "layout": lay,
        "spec_sha256": vc.sha256_file(base_spec), "vip_tree": str(base_tree.resolve()),
        "evidence": [p.name for p in sorted((base_run / "05_qual").glob("qual_evidence*.json"))]})
    if mode == "bugfix":
        copy_into(base_spec, run / "01_spec" / base_spec.name)
        if lay == "flow":
            copy_into(base_run / "02_plan", run / "02_plan")
            copy_into(base_run / "03_arch", run / "03_arch")
        copy_into(base_tree, run / "04_vip" / f"{tag}_vip")
        cfg = run / "04_vip" / f"{tag}_vip" / "spec" / "vip_config.json"
        if cfg.is_file():
            c = json.loads(cfg.read_text(encoding="utf-8"))
            c["version"] = new_version
            cfg.write_text(json.dumps(c, indent=2) + NL, encoding="utf-8", newline=NL)
        st["spec"] = {"source": str(base_spec), "sha256": vc.sha256_file(base_spec)}
    else:
        copy_into(base_spec, run / "01_spec" / base_spec.name)
        (run / "00_change" / "change_request.md").write_text(CHANGE_REQUEST, encoding="utf-8", newline=NL)
        if lay == "external":
            copy_into(base_tree, run / "04_vip" / f"{tag}_vip")
        st["spec"] = {"source": str(base_spec), "sha256": vc.sha256_file(base_spec)}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    d = sub.add_parser("delta")
    d.add_argument("old")
    d.add_argument("new")
    d.add_argument("--out")
    d.add_argument("--json")
    c = sub.add_parser("carry")
    c.add_argument("--evidence", required=True)
    c.add_argument("--base-evidence", required=True)
    c.add_argument("--impact", required=True)
    c.add_argument("--base-run", required=True)
    c.add_argument("--rerun", nargs="*")
    c.add_argument("--bug-log", help="bug_log.csv: regression tests of fixed bugs become evidence entries (kind reg)")
    p = sub.add_parser("adopt")
    p.add_argument("--code", required=True)
    p.add_argument("--out", required=True)
    ly = sub.add_parser("layout")
    ly.add_argument("tree")
    a = ap.parse_args()
    if a.cmd == "layout":
        print(layout_of(Path(a.tree)))
        return 0
    return {"delta": cmd_delta, "carry": cmd_carry, "adopt": cmd_adopt}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
